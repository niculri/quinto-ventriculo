// The snapshot of each database's schema, one file per function and table: `npm run db:schema` writes
// db/<name>/schema/, generated from PGlite with every migration applied.
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { createDatabase } from '../tests/pglite';
import { MIGRATION_ORDER } from './db-types';
import type { DatabaseName } from './db-types';
import { domainsOf } from './schema/domains';
import { SNAPSHOT_DIRECTORY } from './schema/files';
import { renderSnapshot } from './schema/render';
import type { SnapshotFiles } from './schema/render';
import { readCatalogFromPglite } from './schema/read';

const DRAFT_NOTE =
  'The `draft` schema (the preview of the next publication) is not here: `rebuild_draft()` makes it from `public`.\n\n';

const README = (name: DatabaseName) => `# Schema of the ${name} database

A reading copy of what the migrations of \`db/${name}/supabase/migrations\` leave in the \`public\` schema, one file per
function and per table, in a folder per domain. It is generated by \`npm run db:schema\` (PGlite, every migration
applied) and \`db/tests/schema-snapshot-contract.test.ts\` fails when it is out of date. It is not a script to run: the
changes to the database are still the migrations. Every night the private repository compares it with production.

${name === 'content' ? DRAFT_NOTE : ''}Privileges are only those of \`public\`, \`anon\`, \`authenticated\`, \`service_role\` and
\`supabase_auth_admin\`.
`;

export async function generateSnapshot(name: DatabaseName): Promise<SnapshotFiles> {
  const db = await createDatabase(name, MIGRATION_ORDER[name]);
  try {
    const catalog = await readCatalogFromPglite(db, 'public');
    const files = renderSnapshot(catalog, domainsOf(name));
    files.set('README.md', README(name));
    return files;
  } finally {
    await db.close();
  }
}

if (process.argv[1] === import.meta.filename) {
  for (const name of ['users', 'content'] as const) {
    const directory = SNAPSHOT_DIRECTORY(name);
    rmSync(directory, { recursive: true, force: true });
    const files = await generateSnapshot(name);
    for (const [path, content] of files) {
      mkdirSync(dirname(join(directory, path)), { recursive: true });
      writeFileSync(join(directory, path), content);
    }
    console.log(`db/${name}/schema: ${files.size} files`);
  }
}
