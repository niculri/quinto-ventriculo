// Turns a catalog into the files of the snapshot: one per function, table and loose sequence, grouped by domain.
import { SNAPSHOT_ROLES } from './catalog';
import type {
  Catalog,
  CatalogFunction,
  CatalogSequence,
  CatalogTable,
  CatalogTrigger,
  DefaultPrivilege,
  Grant,
} from './catalog';

export type SnapshotFiles = Map<string, string>;

export type ObjectKind = 'function' | 'table' | 'sequence';

/** The domain folder of an object; it throws for one nobody has placed. */
export type DomainOf = (kind: ObjectKind, name: string) => string;

const SCHEMA = 'public';

const HEADER =
  '-- A reading copy of the schema the migrations leave: generated by npm run db:schema, not to be run.';

const COMMANDS: Record<string, string> = {
  r: 'select',
  a: 'insert',
  w: 'update',
  d: 'delete',
  '*': 'all',
};

const quote = (name: string) => (/^[a-z_][a-z0-9_]*$/.test(name) ? name : `"${name}"`);

function groupGrants(grants: Grant[]): Map<string, string[]> {
  const byRole = new Map<string, string[]>();
  for (const { grantee, privilege } of grants) {
    byRole.set(grantee, [...(byRole.get(grantee) ?? []), privilege.toLowerCase()]);
  }
  return byRole;
}

function grantLines(on: string, grants: Grant[]): string[] {
  return [...groupGrants(grants)].map(
    ([role, privileges]) => `grant ${privileges.join(', ')} on ${on} to ${role};`,
  );
}

const TRIGGER_STATES: Record<string, string> = {
  D: 'disable trigger',
  R: 'enable replica trigger',
  A: 'enable always trigger',
};

/** The trigger's definition, and a line for the state of one that does not fire as usual (a disabled one). */
function triggerLines(table: string, trigger: CatalogTrigger): string[] {
  const state = TRIGGER_STATES[trigger.enabled];
  return [
    `${trigger.definition};`,
    ...(state ? [`alter table ${table} ${state} ${quote(trigger.name)};`] : []),
  ];
}

function columnGrantLines(table: string, columns: CatalogTable['columns']): string[] {
  return columns.flatMap((column) =>
    [...groupGrants(column.acl)].map(([role, privileges]) => {
      const columnPrivileges = privileges.map(
        (privilege) => `${privilege} (${quote(column.name)})`,
      );
      return `grant ${columnPrivileges.join(', ')} on table ${table} to ${role};`;
    }),
  );
}

function functionFile(fn: CatalogFunction): string {
  const lines = [HEADER, '', `${fn.definition.trimEnd()};`];
  const signature = `${SCHEMA}.${quote(fn.name)}(${fn.args})`;
  const grants = grantLines(`function ${signature}`, fn.acl);
  if (grants.length) lines.push('', ...grants);
  if (fn.comment)
    lines.push('', `comment on function ${signature} is '${fn.comment.replaceAll("'", "''")}';`);
  return `${lines.join('\n')}\n`;
}

function columnLine(column: CatalogTable['columns'][number]): string {
  const parts = [quote(column.name), column.type];
  if (column.generated === 's') parts.push(`generated always as (${column.default ?? ''}) stored`);
  else if (column.identity === 'a') parts.push('generated always as identity');
  else if (column.identity === 'd') parts.push('generated by default as identity');
  else if (column.default !== null) parts.push(`default ${column.default}`);
  if (column.notNull) parts.push('not null');
  return `  ${parts.join(' ')}`;
}

function policyStatement(table: string, policy: CatalogTable['policies'][number]): string {
  const command = COMMANDS[policy.command] ?? policy.command;
  const clauses = [
    `create policy "${policy.name}" on ${table}`,
    `as ${policy.permissive ? 'permissive' : 'restrictive'}`,
    `for ${command}`,
    `to ${policy.roles.join(', ')}`,
  ];
  if (policy.using !== null) clauses.push(`using (${policy.using})`);
  if (policy.check !== null) clauses.push(`with check (${policy.check})`);
  return `${clauses.join('\n  ')};`;
}

function tableFile(table: CatalogTable): string {
  if (table.relkind !== 'r' && table.relkind !== 'p') {
    throw new Error(`${SCHEMA}.${table.name}: views are not supported`);
  }
  const name = `${SCHEMA}.${quote(table.name)}`;
  const body = [
    ...table.columns.map(columnLine),
    ...table.constraints.map((k) => `  constraint ${quote(k.name)} ${k.definition}`),
  ];
  const withOptions = table.options.length ? ` with (${table.options.join(', ')})` : '';
  const blocks = [HEADER, `create table ${name} (\n${body.join(',\n')}\n)${withOptions};`];
  if (table.indexes.length) blocks.push(table.indexes.map((i) => `${i.definition};`).join('\n'));
  if (table.triggers.length) {
    blocks.push(table.triggers.flatMap((t) => triggerLines(name, t)).join('\n'));
  }
  if (table.rowSecurity) {
    const force = table.forceRowSecurity ? `\nalter table ${name} force row level security;` : '';
    blocks.push(`alter table ${name} enable row level security;${force}`);
  }
  if (table.policies.length)
    blocks.push(table.policies.map((p) => policyStatement(name, p)).join('\n\n'));
  const grants = [
    ...grantLines(`table ${name}`, table.acl),
    ...columnGrantLines(name, table.columns),
  ];
  if (grants.length) blocks.push(grants.join('\n'));
  if (table.comment) {
    blocks.push(`comment on table ${name} is '${table.comment.replaceAll("'", "''")}';`);
  }
  return `${blocks.join('\n\n')}\n`;
}

function sequenceFile(sequence: CatalogSequence): string {
  const name = `${SCHEMA}.${quote(sequence.name)}`;
  const blocks = [HEADER, `create sequence ${name} ${sequence.definition};`];
  const grants = grantLines(`sequence ${name}`, sequence.acl);
  if (grants.length) blocks.push(grants.join('\n'));
  return `${blocks.join('\n\n')}\n`;
}

function defaultPrivilegeLine(entry: DefaultPrivilege): string[] {
  const where = entry.schema === null ? '' : ` in schema ${entry.schema}`;
  if (entry.grants.length === 0) {
    const roles = SNAPSHOT_ROLES.join(', ');
    return [
      `alter default privileges for role postgres${where} revoke all on ${entry.objects} from ${roles};`,
    ];
  }
  return [...groupGrants(entry.grants)].map(
    ([role, privileges]) =>
      `alter default privileges for role postgres${where} grant ${privileges.join(', ')} on ${entry.objects} to ${role};`,
  );
}

/** What does not belong to one object: the extensions, the triggers on other schemas' tables (auth.users) and the default privileges. */
function databaseFile(catalog: Catalog): string {
  const blocks = [HEADER];
  if (catalog.extensions.length) {
    blocks.push(catalog.extensions.map((e) => `create extension if not exists "${e}";`).join('\n'));
  }
  if (catalog.externalTriggers.length) {
    blocks.push(catalog.externalTriggers.flatMap((t) => triggerLines(t.table, t)).join('\n'));
  }
  blocks.push(catalog.defaultPrivileges.flatMap(defaultPrivilegeLine).join('\n'));
  return `${blocks.join('\n\n')}\n`;
}

export function renderSnapshot(catalog: Catalog, domainOf: DomainOf): SnapshotFiles {
  const files: SnapshotFiles = new Map();
  const add = (path: string, content: string) => {
    if (files.has(path)) throw new Error(`Two objects write ${path}`);
    files.set(path, content);
  };
  for (const fn of catalog.functions) {
    add(`${domainOf('function', fn.name)}/functions/${fn.name}.sql`, functionFile(fn));
  }
  for (const table of catalog.tables) {
    add(`${domainOf('table', table.name)}/tables/${table.name}.sql`, tableFile(table));
  }
  for (const sequence of catalog.sequences) {
    add(
      `${domainOf('sequence', sequence.name)}/sequences/${sequence.name}.sql`,
      sequenceFile(sequence),
    );
  }
  add('_database.sql', databaseFile(catalog));
  return files;
}
